const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
function scan(directory) {
	return fs.readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap(entry => {
		const relative = `${directory}/${entry.name}`;
		return entry.isDirectory() ? scan(relative) : /\.(mp3|ogg|wav|m4a|aac|flac|opus)$/i.test(entry.name) ? [relative] : [];
	});
}
const tracks = scan("audio/bgm").sort();
const output = `/* Generated by devTools/generate-music-library.cjs. */\nsetup.pocketMusicTracks = ${JSON.stringify(tracks, null, "\t")};\n`;
const destination = path.join(root, "game/special-xchange/DoLXAddition/pocket/music-library.js");
if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== output) fs.writeFileSync(destination, output);
